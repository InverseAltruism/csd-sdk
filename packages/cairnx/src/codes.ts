/** A reason code of the applied log or of record validation. */
export type ReasonCode = keyof typeof TABLE;
/** The codes of an applied record (`ok: true`). */
export type AppliedCode = { [K in ReasonCode]: (typeof TABLE)[K] extends "applied" ? K : never }[ReasonCode];
/** The codes of a refused record (`ok: false`). */
export type RefusalCode = Exclude<ReasonCode, AppliedCode>;
/** The codes of a record that does not parse (explainRecord, RecordError, the log's `invalid` entries). */
export type RecordCode = Extract<ReasonCode, `RECORD_${string}`>;

/** Every code, in table order. */
export const REASON_CODES: readonly ReasonCode[] = Object.freeze(Object.keys(TABLE) as ReasonCode[]);
/** Each code's outcome. A reader meets codes added after its release, so it classifies an unknown code by the entry's `ok`. */
export const REASON_CODE_OUTCOME: Readonly<Record<ReasonCode, "applied" | "refused">> = Object.freeze({ ...TABLE });
/** The refusals CONVENTION §40 calls caps: per-address rules that count the proposer's other names or offers. */
