#!/usr/bin/env node
// The package's build: derives the log from cairnx-core's committed fixture and the deltas (shipped.mjs), refuses
// unless the derived pin repeats pin.json in every field but `core`, and writes dist/index.js (PIN, with log() over
// the log text held as one string literal, so Node, bundlers and an extension worker load it alike) and its types.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PIN_FILE, ROOT, derivedPin } from "./shipped.mjs";

const pin = JSON.parse(readFileSync(PIN_FILE, "utf8"));
let d;
try { d = await derivedPin(pin); } catch (e) { console.error(`cairnx-pin build: ${e instanceof Error ? e.message : String(e)}`); process.exit(1); }
const dist = join(ROOT, "dist");
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
writeFileSync(join(dist, "index.js"), [
  "// Generated by scripts/build.mjs from pin.json and the log derived from the fixture and the deltas; do not edit.",
  `const LOG = ${JSON.stringify(new TextDecoder().decode(d.log))};`,
  `export const PIN = Object.freeze({ ...${JSON.stringify(pin)}, log: async () => new TextEncoder().encode(LOG) });`,
  "",
].join("\n"));
writeFileSync(join(dist, "index.d.ts"), 'import type { Pin } from "@inversealtruism/cairnx-replica";\nexport declare const PIN: Pin;\n');
console.log(`cairnx-pin build: the pin at ${pin.height}, ${d.log.length} log bytes, sha256 ${pin.logSha256}`);
