#!/usr/bin/env node
// The wallet's two generated source files, rendered from anchors.json byte for byte: src/core/spvanchors.ts (the
// floor, the chunk and the entries) and src/core/spvnewest.ts (the newest entry's height alone).
//   node render-wallet.mjs anchors|newest [<anchors.json>, else the package's own]     prints the file to stdout
import { readFileSync, realpathSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { TABLE, firstChunk, parseTable, validateTable } from "./table.mjs";

export function renderSpvAnchors(t) {
  validateTable(t);
  return [
    "// Generated by scripts/update-spv-anchors.mjs (usage at its top); do not edit.",
    `// SPV_ANCHORS[i] is the block hash at height SPV_CHUNK * (${firstChunk(t.floor.height, t.chunk)} + i) + SPV_CHUNK - 1.`,
    `export const SPV_FLOOR = { height: ${t.floor.height}, hash: "${t.floor.hash}" } as const;`,
    `export const SPV_CHUNK = ${t.chunk};`,
    "export const SPV_ANCHORS: readonly string[] = [",
    ...t.anchors.map((a) => `  "${a.hash}", // ${a.height}`),
    "];",
    "",
  ].join("\n");
}

export function renderSpvNewest(t) {
  validateTable(t);
  return [
    "// Generated by scripts/update-spv-anchors.mjs with spvanchors.ts; do not edit.",
    "// The height of the release anchor table's newest entry, without the table (src/core/chainbound.ts).",
    `export const SPV_NEWEST_HEIGHT = ${t.anchors.at(-1).height};`,
    "",
  ].join("\n");
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [which, file = TABLE, ...rest] = process.argv.slice(2);
  const render = { anchors: renderSpvAnchors, newest: renderSpvNewest }[which ?? ""];
  if (!render || rest.length > 0) {
    console.error("usage: render-wallet.mjs anchors|newest [<anchors.json>]");
    process.exit(2);
  }
  try { process.stdout.write(render(parseTable(readFileSync(file, "utf8")))); } catch (e) {
    console.error(`render-wallet: ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  }
}
