#!/usr/bin/env node
// The package's build: refuses unless anchors.json passes its shape rules and is its own canonical text (table.mjs),
// then writes dist/index.js (ANCHORS, the table as a deep-frozen literal, so Node, bundlers and an extension worker
// load it alike) and its types.
import { mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, parseTable } from "./table.mjs";

const TYPES = `export interface Anchor { readonly height: number; readonly hash: string }
export interface AnchorTable {
  readonly format: 1;
  readonly chunk: number;
  readonly floor: Anchor;
  readonly activationRoot: Anchor;
  readonly anchors: readonly Anchor[];
}
export declare const ANCHORS: AnchorTable;
`;

/** Builds `root`'s dist from its anchors.json; throws when the table is refused. Returns the table. */
export function build(root = ROOT) {
  const table = parseTable(readFileSync(join(root, "anchors.json"), "utf8"));
  const dist = join(root, "dist");
  rmSync(dist, { recursive: true, force: true });
  mkdirSync(dist);
  writeFileSync(join(dist, "index.js"), [
    "// Generated by scripts/build.mjs from anchors.json; do not edit.",
    "const deepFreeze = (v) => { for (const x of Object.values(v)) if (typeof x === \"object\" && x !== null) deepFreeze(x); return Object.freeze(v); };",
    `export const ANCHORS = /* @__PURE__ */ deepFreeze(${JSON.stringify(table)});`,
    "",
  ].join("\n"));
  writeFileSync(join(dist, "index.d.ts"), TYPES);
  return table;
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const t = build();
    console.log(`csd-anchors build: ${t.anchors.length} entries, ${t.anchors[0].height} to ${t.anchors.at(-1).height}, floor ${t.floor.height}`);
  } catch (e) {
    console.error(`csd-anchors build: ${e instanceof Error ? e.message : String(e)}`);
    process.exit(1);
  }
}
